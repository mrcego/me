/**
 * After `nuxt generate`, scan prerendered HTML for executable inline scripts,
 * emit sha256 CSP hashes, and write Netlify `_headers` without script-src
 * 'unsafe-inline'. Non-executable script types (JSON-LD / JSON payload) are ignored.
 *
 * Usage: node scripts/write-csp-headers.mjs
 * Honors NUXT_OUTPUT_DIR (default `.output`).
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';

const outputRoot = process.env.NUXT_OUTPUT_DIR || '.output';
const publicDir = join(process.cwd(), outputRoot, 'public');

if (!existsSync(publicDir)) {
  console.error(`[csp] Missing ${publicDir} — run nuxt generate first`);
  process.exit(1);
}

/** @param {string} dir */
function walkHtml(dir) {
  /** @type {string[]} */
  const files = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) files.push(...walkHtml(full));
    else if (name.endsWith('.html')) files.push(full);
  }
  return files;
}

/**
 * @param {string} attrs
 * @param {string} body
 */
function isExecutableInlineScript(attrs, body) {
  if (!body.trim()) return false;
  if (/\bsrc\s*=/i.test(attrs)) return false;
  const typeMatch = attrs.match(/\btype\s*=\s*["']([^"']+)["']/i);
  const type = (typeMatch?.[1] || 'text/javascript').toLowerCase().trim();
  // Only classic/module inline JS needs hashes. JSON-LD / Nuxt payload are data.
  if (type === 'application/ld+json' || type === 'application/json' || type === 'importmap') {
    return false;
  }
  return (
    type === 'text/javascript' ||
    type === 'application/javascript' ||
    type === 'module' ||
    type === '' ||
    type === 'text/javascript;charset=utf-8'
  );
}

/** @param {string} body */
function sha256Hash(body) {
  return `'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`;
}

const hashes = new Set();
let inlineCount = 0;

for (const file of walkHtml(publicDir)) {
  const html = readFileSync(file, 'utf8');
  const re = /<script\b([^>]*)>([\s\S]*?)<\/script>/gi;
  let match;
  while ((match = re.exec(html)) !== null) {
    const attrs = match[1] || '';
    const body = match[2] ?? '';
    if (!isExecutableInlineScript(attrs, body)) continue;
    hashes.add(sha256Hash(body));
    inlineCount += 1;
    console.log(`[csp] hash ${relative(publicDir, file)} (${body.length} bytes)`);
  }
}

if (hashes.size === 0) {
  console.error('[csp] No executable inline scripts found — refusing to write a broken CSP');
  process.exit(1);
}

const scriptSrc = ["'self'", ...[...hashes].sort()].join(' ');

const csp = [
  "default-src 'self'",
  "base-uri 'self'",
  "object-src 'none'",
  "frame-ancestors 'none'",
  "form-action 'self'",
  "img-src 'self' data:",
  "font-src 'self'",
  // Vue/Nuxt inline critical CSS into HTML; keep style hashes out of scope for now.
  "style-src 'self' 'unsafe-inline'",
  `script-src ${scriptSrc}`,
  "connect-src 'self'",
  "manifest-src 'self'",
  // Enforce Trusted Types on DOM XSS sinks (default policy registered in theme-init).
  "require-trusted-types-for 'script'",
  'trusted-types default',
  'upgrade-insecure-requests',
].join('; ');

const headers = `\
#
# Generated by scripts/write-csp-headers.mjs — do not edit by hand.
# Inline script hashes: ${hashes.size} unique / ${inlineCount} occurrences
#
/*
  Content-Security-Policy: ${csp}
`;

const outFile = join(publicDir, '_headers');
writeFileSync(outFile, headers, 'utf8');

// Self-check: every executable inline script in the publish tree must be allowlisted.
const missing = [];
for (const file of walkHtml(publicDir)) {
  const html = readFileSync(file, 'utf8');
  const re = /<script\b([^>]*)>([\s\S]*?)<\/script>/gi;
  let match;
  while ((match = re.exec(html)) !== null) {
    const attrs = match[1] || '';
    const body = match[2] ?? '';
    if (!isExecutableInlineScript(attrs, body)) continue;
    const hash = sha256Hash(body);
    if (!hashes.has(hash) || !csp.includes(hash)) {
      missing.push(`${relative(publicDir, file)} ${hash}`);
    }
  }
}

if (missing.length) {
  console.error('[csp] Self-check failed — hashes missing from CSP:');
  for (const row of missing) console.error(`  ${row}`);
  process.exit(1);
}

console.log(`[csp] Wrote ${outFile}`);
console.log(`[csp] script-src hashes: ${hashes.size} (no 'unsafe-inline')`);
console.log('[csp] Self-check OK — all inline scripts allowlisted');
console.log(
  '[csp] Reminder: Netlify [build.processing] skip_processing must be true or HTML rewrites break these hashes.',
);
